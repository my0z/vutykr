// 소개와 개인정보처리방침과 이용약관 (사이트 이름과 문의처만 바꿔서 다섯 사이트가 함께 쓴다)
import { DISC } from '../sites/index.js';

const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const DATE = '2026-11-19';

const sec = list => list.map(([h, p]) => `<section><h2>${esc(h)}</h2>${(Array.isArray(p) ? p : [p]).map(t => `<p>${esc(t)}</p>`).join('')}</section>`).join('');

export function legalPage(site, kind) {
  const n = site.name;
  const contact = site.contact
    ? `개인정보와 관련한 문의는 ${site.contact}로 보내 주세요.`
    : '개인정보와 관련한 문의는 수다방 글쓰기로 남겨 주세요. 확인 후 안내해 드립니다.';
  if (kind === 'about') {
    return {
      title: `${n} 소개 | ${n}`, desc: `${n}이 어떤 사이트인지와 상품 정보를 어떻게 가져오는지 안내합니다`,
      body: `<article class="ip gd ssr"><section><h1>${esc(n)} 소개</h1><p>${esc(site.intro)}</p></section>` + sec([
        ['이 사이트는 무엇인가요', `${n}은 쿠팡의 인기 상품을 분야별로 모아 보여 주는 소개 사이트입니다. 상품을 직접 판매하지 않으며 구매와 배송과 교환과 환불은 쿠팡에서 처리합니다.`],
        ['수수료 안내', `${DISC} 이용자가 지불하는 가격은 달라지지 않습니다.`],
        ['상품 정보는 어디서 가져오나요', '쿠팡 파트너스가 제공하는 상품 데이터를 불러와 보여 줍니다. 한 번에 모든 분야를 갱신하지 않고 분야를 돌아가며 불러오므로 상품과 가격이 갱신되는 시점은 분야마다 다를 수 있습니다. 실제 가격과 재고는 쿠팡에서 바뀔 수 있으니 구매 전에 꼭 확인하세요.'],
        ['이미지 안내', '상품 이미지는 쿠팡이 제공하는 이미지를 그대로 불러옵니다. 사이트 상단의 인물과 동물 배너 사진은 인공지능으로 만든 가상의 이미지이며 실제 사람이나 동물의 사진이 아닙니다.'],
        ['구매 가이드 안내', '분야별 구매 가이드는 일반적인 정보를 정리한 글이며 전문가의 조언을 대신하지 않습니다. 안전이나 건강과 관련된 제품은 전문가와 상담한 뒤 선택하세요.'],
        ['문의', contact]
      ]) + '</article>'
    };
  }
  if (kind === 'privacy') {
    return {
      title: `개인정보처리방침 | ${n}`, desc: `${n}이 어떤 정보를 수집하고 어떻게 쓰는지 안내합니다`,
      body: `<article class="ip gd ssr"><section><h1>개인정보처리방침</h1><p>${esc(n)}은 이용자의 개인정보를 소중하게 다루며 아래와 같이 처리합니다. 시행일은 ${DATE}입니다.</p></section>` + sec([
        ['수집하는 정보', [
          '방문 기록: 접속 시각과 국가와 도시와 기기 종류와 브라우저와 운영체제와 유입 경로와 언어 설정과 접속 주소를 변환한 값을 수집합니다. 접속 주소는 원본을 저장하지 않고 셋째 자리를 가린 값과 되돌릴 수 없는 해시 값만 보관합니다.',
          '수다방 이용: 글과 댓글을 쓸 때 입력한 닉네임과 내용과 비밀번호의 해시 값을 수집합니다. 비밀번호 원문은 저장하지 않습니다.'
        ]],
        ['이용 목적', '사이트 이용 통계와 서비스 개선과 부정 이용 방지와 수다방 운영을 위해서만 사용합니다. 광고 목적의 이용자 식별이나 프로파일링은 하지 않습니다.'],
        ['보관 기간', '방문 기록은 90일이 지나면 자동으로 삭제합니다. 수다방 글과 댓글은 작성자가 비밀번호로 삭제하거나 운영자가 삭제할 때까지 보관합니다.'],
        ['제3자 제공과 외부 이동', '수집한 정보를 제3자에게 판매하거나 제공하지 않습니다. 상품을 누르면 쿠팡으로 이동하며 이동한 뒤에는 쿠팡의 개인정보 처리 방침과 쿠키 정책이 적용됩니다. 쿠팡은 구매 추적을 위해 쿠키를 사용할 수 있습니다.'],
        ['쿠키', `${n}은 이용자를 식별하는 광고 쿠키를 사용하지 않습니다. 브라우저 설정에서 쿠키를 차단해도 사이트를 이용할 수 있습니다.`],
        ['이용자의 권리', '수다방에 쓴 글은 비밀번호로 직접 삭제할 수 있습니다. 그 밖에 열람과 삭제 요청은 아래 문의처로 알려 주세요.'],
        ['안전성 확보 조치', '모든 통신은 암호화된 연결(HTTPS)로 처리하고 관리자 화면은 비밀번호로 보호합니다. 접속 주소는 가린 값과 해시 값만 저장합니다.'],
        ['문의처', contact],
        ['방침 변경', '내용이 바뀌면 이 페이지에 시행일과 함께 알립니다.']
      ]) + '</article>'
    };
  }
  return {
    title: `이용약관 | ${n}`, desc: `${n} 이용 조건과 책임 범위를 안내합니다`,
    body: `<article class="ip gd ssr"><section><h1>이용약관</h1><p>${esc(n)}을 이용하면 아래 내용에 동의한 것으로 봅니다. 시행일은 ${DATE}입니다.</p></section>` + sec([
      ['서비스 성격', `${n}은 쿠팡의 상품을 소개하는 사이트입니다. 상품의 판매와 배송과 교환과 환불은 쿠팡이 처리하며 ${n}은 판매 당사자가 아닙니다. ${DISC}`],
      ['정보의 정확성', '상품 이름과 가격과 재고와 이미지는 쿠팡이 제공하는 정보를 불러온 것으로 실제와 다를 수 있습니다. 구매를 결정하기 전에 쿠팡에서 최신 정보를 확인하세요. 이 사이트의 글은 일반적인 참고 정보입니다.'],
      ['게시물', '수다방의 글과 댓글은 작성자가 책임집니다. 광고와 욕설과 개인정보 노출과 불법 정보와 타인을 비방하는 글은 예고 없이 삭제할 수 있습니다.'],
      ['책임의 한계', `${n}은 쿠팡과 판매자가 제공하는 상품과 서비스에 대해 책임지지 않습니다. 외부 사이트로 이동한 뒤 일어난 일은 해당 사이트의 정책을 따릅니다.`],
      ['지적 재산', '상품 이미지와 상품 정보에 대한 권리는 쿠팡과 판매자에게 있습니다. 이 사이트의 구성과 글을 무단으로 복제하거나 배포할 수 없습니다.'],
      ['약관 변경', '약관이 바뀌면 이 페이지에 시행일과 함께 알립니다.']
    ]) + '</article>'
  };
}
